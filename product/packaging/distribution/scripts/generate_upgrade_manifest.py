#!/usr/bin/env python3
"""
Generate upgrade-manifest.json from per-platform build artifacts.

Usage:
    python generate_upgrade_manifest.py \
        --artifacts-dir ./artifacts \
        --base-url https://github.com/owner/repo/releases/download/v2026.04.0 \
        --release-config ./product/packaging/distribution/release-config.json \
        --output ./artifacts/upgrade-manifest.json \
        [--mandatory] \
        [--release-notes "text or empty"]

Inputs:
    - Per-platform package-info-<Label>.json (generated by CMake, renamed by CI):
        { "version": "2026.04.0.1523" }
    - Per-platform .sha256 files (generated by CI)
    - release-config.json (product/packaging/distribution/):
        { "upgrade": { "minVersion": "...", "mandatory": false } }

Output:
    upgrade-manifest.json uploaded alongside release assets.
"""

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


# Archives remain release assets, but are never offered for in-app upgrades.
INSTALLER_FORMATS = {
    "Windows": ("exe",),
    "Linux": ("deb", "rpm"),
    "macOS": ("dmg",),
}

PLATFORM_LABEL_TO_KEY = {
    "Windows": "windows-x64",
    "Linux":   "linux-x64",
    "macOS":   "macos-arm64",
}


def find_installer_package(artifacts_dir: Path, label: str,
                           package_format: str, version: str) -> Path:
    """Require one installer for the platform and the exact CMake version."""
    matches = sorted(
        path for path in artifacts_dir.rglob(f"*-{label}.{package_format}")
        if path.is_file()
    )
    if len(matches) != 1:
        found = ", ".join(str(path) for path in matches) or "none"
        raise ValueError(
            f"Expected exactly one {label}/{package_format} installer, "
            f"found {len(matches)}: {found}"
        )
    package_path = matches[0]
    expected_suffix = f"-{version}-{label}.{package_format}"
    if not package_path.name.endswith(expected_suffix):
        raise ValueError(
            f"Installer version does not match package-info version {version}: "
            f"{package_path.name} (expected suffix {expected_suffix})"
        )
    return package_path


def read_sha256(package_path: Path) -> str:
    """Read SHA-256 from companion .sha256 file, or compute it."""
    sha_file = Path(str(package_path) + ".sha256")
    if sha_file.exists():
        fields = sha_file.read_text().strip().split()
        if not fields or not re.fullmatch(r"[0-9a-fA-F]{64}", fields[0]):
            raise ValueError(f"Invalid SHA-256 file: {sha_file}")
        return fields[0].lower()

    # Fallback: compute from file
    h = hashlib.sha256()
    with open(package_path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    parser = argparse.ArgumentParser(description="Generate upgrade-manifest.json")
    parser.add_argument("--artifacts-dir", required=True,
                        help="Directory containing downloaded build artifacts")
    parser.add_argument("--base-url", required=True,
                        help="Base download URL for release assets")
    parser.add_argument("--release-config", default="product/packaging/distribution/release-config.json",
                        help="Path to release-config.json")
    parser.add_argument("--output", required=True,
                        help="Output path for upgrade-manifest.json")
    parser.add_argument("--mandatory", action="store_true",
                        help="Override: force mandatory upgrade")
    parser.add_argument("--release-notes", default="",
                        help="Release notes text (empty = filled later by GitHub)")
    args = parser.parse_args()

    artifacts_dir = Path(args.artifacts_dir)

    # ── Read release-config.json ──
    release_config = {"upgrade": {"minVersion": "", "mandatory": False}}
    config_path = Path(args.release_config)
    if config_path.exists():
        with open(config_path) as f:
            release_config = json.load(f)
        print(f"  Read release config from {config_path}")
    else:
        print(f"  Warning: {config_path} not found, using defaults")

    upgrade_cfg = release_config.get("upgrade", {})
    min_version = upgrade_cfg.get("minVersion", "")
    mandatory = args.mandatory or upgrade_cfg.get("mandatory", False)

    # ── Collect per-platform package-info-*.json files ──
    info_files = sorted(artifacts_dir.rglob("package-info-*.json"))
    if not info_files:
        raise ValueError(f"No package-info-*.json files found in {artifacts_dir}")

    version = None
    packages = {}

    for info_file in info_files:
        with open(info_file) as f:
            info = json.load(f)

        label = info_file.stem.removeprefix("package-info-")
        if label not in INSTALLER_FORMATS:
            raise ValueError(f"Unsupported package-info platform: {info_file.name}")
        platform_key = PLATFORM_LABEL_TO_KEY[label]
        if platform_key in packages:
            raise ValueError(f"Duplicate package-info for {platform_key}: {info_file}")

        pkg_version = info.get("version") if isinstance(info, dict) else None
        if (not isinstance(pkg_version, str)
                or not re.fullmatch(r"[0-9]+(?:\.[0-9]+)*", pkg_version)):
            raise ValueError(f"Invalid numeric dotted version in {info_file}")
        if version is None:
            version = pkg_version
        elif version != pkg_version:
            raise ValueError(
                f"Package-info version mismatch: {version} vs {pkg_version} "
                f"for {platform_key}"
            )

        platform_packages = {}
        for package_format in INSTALLER_FORMATS[label]:
            pkg_path = find_installer_package(
                artifacts_dir, label, package_format, pkg_version)
            sha256 = read_sha256(pkg_path)
            size = pkg_path.stat().st_size
            if size <= 0:
                raise ValueError(f"Installer must not be empty: {pkg_path}")

            platform_packages[package_format] = {
                "url": f"{args.base_url.rstrip('/')}/{pkg_path.name}",
                "sha256": sha256,
                "size": size,
            }
            print(
                f"  {platform_key}/{package_format}: {pkg_path.name} "
                f"({size} bytes, sha256={sha256[:16]}...)"
            )
        packages[platform_key] = platform_packages

    # ── Assemble manifest ──
    manifest = {
        "schemaVersion": 2,
        "version": version,
        "releaseDate": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "releaseNotes": args.release_notes,
        "mandatory": mandatory,
        "minVersion": min_version,
        "packages": packages,
    }

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(manifest, f, indent=2)

    print(f"\n  Generated {output_path}")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        sys.exit(1)
